// Merges apps/server/src/docs/common.openapi.ts + apps/server/src/docs/modules/*.openapi.ts
// into apps/server/src/docs/openapi.ts. Run via `npm run docs:generate` after adding/editing a module.
import { writeFileSync } from 'fs';
import { join } from 'path';
import * as common from './common.openapi';
import * as health from './modules/health.openapi';
import * as auth from './modules/auth.openapi';
import * as student from './modules/student.openapi';
import * as admin from './modules/admin.openapi';
import * as supportStaff from './modules/support-staff.openapi';
import * as superAdmin from './modules/super-admin.openapi';

// Add new API modules here — nothing else in this file needs to change.
const modules = [health, auth, student, admin, supportStaff, superAdmin];

function mergePaths(): Record<string, unknown> {
  return modules.reduce((acc, mod) => Object.assign(acc, mod.paths), {} as Record<string, unknown>);
}

function mergeSchemas(): Record<string, unknown> {
  return modules.reduce((acc, mod) => Object.assign(acc, 'schemas' in mod ? mod.schemas : {}), {
    ...common.schemas,
  } as Record<string, unknown>);
}

const openApiDocument = {
  openapi: '3.0.3',
  info: common.info,
  servers: common.servers,
  tags: common.tags,
  components: {
    securitySchemes: common.securitySchemes,
    schemas: mergeSchemas(),
  },
  paths: mergePaths(),
};

const banner = `// AUTO-GENERATED by apps/server/src/docs/generate-openapi.ts — run \`npm run docs:generate\` to rebuild.
// Do not hand-edit; change the relevant file in apps/server/src/docs/modules/ (or common.openapi.ts) instead.
`;

const outputPath = join(__dirname, 'openapi.ts');
const contents = `${banner}export const openApiDocument = ${JSON.stringify(openApiDocument, null, 2)};\n`;

writeFileSync(outputPath, contents, 'utf8');
console.log(`OpenAPI spec written to ${outputPath}`);
